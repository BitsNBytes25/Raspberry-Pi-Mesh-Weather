import asyncio
import logging

from raspberry_pi_mesh_weather.libs.config import config
from raspberry_pi_mesh_weather.libs.commands import command_catalog
from raspberry_pi_mesh_weather.services.service import Service

try:
	from sentence_transformers import SentenceTransformer
except ImportError:
	SentenceTransformer = None


class AiService(Service):
	"""
	Runs an in-process sentence transformer as the local command resolver,
	classifying unrecognized direct messages into a known command.

	The model only ever selects from the existing command catalog (per-command
	anchors are the command functions' docstring lines, embedded once in
	`load()`).  Replies are always generated by the normal commands.  Exact
	command/alias matches are handled before this service is consulted (see
	`resolve_message` in libs/commands/handler.py).  If the model is not
	loaded, embedding fails, or no anchor is close enough to the message
	(`ai.threshold`), resolution yields None and the existing "I don't
	understand that command" response is sent.
	"""

	def __init__(self):
		super().__init__()
		self._model = None
		self._embeddings = None
		self._anchor_count = 0

	def get_name(self):
		return 'AI Command Resolver (sentence-transformers)'

	def _index_anchors(self, model):
		"""
		Embed every command anchor once and cache the vectors per command.

		Anchors are the non-empty lines of each command function's docstring,
		plus its registered aliases (see `command_catalog`).  Returns the number
		of anchors indexed, or 0 when there is nothing to index.
		"""
		catalog = command_catalog()
		texts = [anchor for entry in catalog for anchor in entry['anchors']]
		if not texts:
			return 0

		vectors = model.encode(texts, normalize_embeddings=True)
		embeddings = {}
		offset = 0
		for entry in catalog:
			anchors = entry['anchors']
			embeddings[entry['name']] = list(vectors[offset:offset + len(anchors)])
			offset += len(anchors)
		self._embeddings = embeddings
		self._anchor_count = len(texts)
		return self._anchor_count

	async def load(self) -> bool:
		if not config.ai.enabled:
			logging.info('AI command resolver disabled in configuration')
			return False
		if not config.ai.model_path:
			logging.error('ai.enabled is true but ai.model_path is empty; AI command resolver not loaded')
			return False
		if SentenceTransformer is None:
			logging.error(
				'AI command resolver not loaded: sentence-transformers is not installed. '
				'Run `uv sync --group ai` to add the AI dependency group.'
			)
			return False

		try:
			self._model = await asyncio.to_thread(
				SentenceTransformer, config.ai.model_path
			)
			indexed = await asyncio.to_thread(self._index_anchors, self._model)
		except Exception as e:
			self._model = None
			logging.error(
				'AI command resolver could not load model %s: %s',
				config.ai.model_path,
				e,
			)
			return False

		if not indexed:
			self._model = None
			logging.error('AI command resolver could not index command anchors; not loaded')
			return False

		self.running = True
		logging.info(
			'AI command resolver ready (%s; %d anchors indexed across %d commands)',
			config.ai.model_path,
			self._anchor_count,
			len(self._embeddings),
		)
		return True

	async def stop(self):
		# Drop references to free the model's memory on a Pi.
		self._model = None
		self._embeddings = None
		self.running = False

	async def test(self):
		if self._model is not None:
			logging.info(
				'AI command resolver ready. Model: %s (threshold %s, %d anchors indexed)',
				config.ai.model_path,
				config.ai.threshold,
				self._anchor_count,
			)
		else:
			logging.info('AI command resolver not running (ai.enabled is false or load failed)')

	def resolve(self, text: str) -> str | None:
		"""
		Map `text` onto a command by embedding it and comparing against the
		cached anchor embeddings.

		:return: the best-matching command name when its closest anchor score is
			at or above `ai.threshold`, else None (model not loaded, embedding
			failed, or nothing close enough).
		"""
		if self._model is None or self._embeddings is None:
			return None
		try:
			embedding = self._model.encode(text, normalize_embeddings=True)
		except Exception as e:
			logging.warning('AI command resolver embedding failed: %s', e)
			return None

		best_name, best_score = None, -1.0
		flat = embedding.reshape(-1)
		for name, vectors in self._embeddings.items():
			for vector in vectors:
				score = float(flat.dot(vector))
				if score > best_score:
					best_score, best_name = score, name

		if best_name is not None and best_score >= config.ai.threshold:
			return best_name
		return None

	async def resolve_async(self, text: str) -> str | None:
		# Worker-thread resolution so the daemon's event loop is never
		# blocked by the (potentially slow) model call.
		return await asyncio.to_thread(self.resolve, text)


_ai_service: AiService | None = None


def set_ai_service(service: AiService):
	global _ai_service
	_ai_service = service


def get_ai_service() -> AiService | None:
	return _ai_service
